"""Compare cached outputs in one pixel frame; no training labels or inference."""
from pathlib import Path
import json
import pickle
import sys

sys.path.append(str(Path(__file__).resolve().parent.parent / '.venv/lib/python3.14/site-packages'))

import cv2
import numpy as np
from affine import Affine
from pyproj import Transformer
from rasterio.io import MemoryFile
from scipy import ndimage as ndi
from shapely.geometry import Polygon
from shapely.ops import unary_union
from shapely import make_valid
from shapely.validation import explain_validity
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parent
BASE = ROOT.parent
sys.path.insert(0, str(ROOT / 'vendor'))
from geo_export import labels_to_geojson


def rmse_for_region(mask, dsm):
    interior = ndi.binary_erosion(mask, iterations=3)
    yy, xx = np.nonzero(interior & np.isfinite(dsm))
    if len(xx) < 20:
        return None
    xy = np.c_[xx * .1, yy * .1, np.ones(len(xx))]
    z = dsm[yy, xx]
    coefficients = np.linalg.lstsq(xy, z, rcond=None)[0]
    residual = z - xy @ coefficients
    return {'interior_pixels': len(xx), 'refit_rmse_m': float(np.sqrt(np.mean(residual ** 2))),
            'refit_coefficients_image_xy': coefficients.tolist()}


def main():
    output = ROOT / 'outputs'
    manifest = json.loads((output / 'trial-manifest.json').read_text())
    arrays = np.load(output / 'warm-arrays.npz')
    cold = np.load(output / 'cold-arrays.npz')
    geo = json.loads((output / 'warm-geojson.json').read_text())
    planes = json.loads((output / 'warm-planes.json').read_text())
    source = pickle.loads((BASE / 'data/inputs.pkl').read_bytes())
    crop = manifest['crop']
    with MemoryFile(source['inputs']['rgb']) as mem, mem.open() as src:
        source_tf = src.transform
        source_crs = src.crs
    origin = source['raw']['origin']
    ox, oy = Transformer.from_crs(4326, source_crs, always_xy=True).transform(
        origin['longitude'], origin['latitude'])
    common_tf = Affine.translation(ox, oy) * source['aligned']['transform']
    crop_tf = source_tf * Affine.translation(crop['cmin'], crop['rmin'])
    crop_to_common = ~common_tf * crop_tf
    local_to_common = ~source['aligned']['transform']
    shape = source['aligned']['rgb'].shape[:2]
    photo = source['aligned']['rgb']
    h, w = arrays['mask'].shape
    west, south, east, north = manifest['bounds']

    def geo_to_crop(ring):
        return np.array([[(x-west)/(east-west)*w, (north-y)/(north-south)*h] for x, y in ring])

    def transform_ring(ring, tf):
        return np.array([tf * tuple(p) for p in ring])

    roof_polygons = []
    stock_polygons = []
    for feature in geo['features']:
        ring = geo_to_crop(feature['geometry']['coordinates'][0])
        stock_polygons.append(Polygon(ring))
        roof_polygons.append(transform_ring(ring, crop_to_common))

    source_polygons = [transform_ring(face['polygon'], local_to_common)
                       for face in source['raw']['faces'] if len(face['polygon']) >= 3]
    previous = json.loads((BASE / 'outputs/phase2-structure.json').read_text())
    previous_polygons = [transform_ring(part['polygon'], local_to_common)
                         for face in previous['roof_faces'] for part in face['parts']]

    def display(ax, title, polygons=None):
        ax.imshow(photo, interpolation='nearest')
        if polygons:
            for ring in polygons:
                closed = np.vstack([ring, ring[0]])
                ax.plot(closed[:, 0] - .5, closed[:, 1] - .5, color='#50d4f2', lw=1.15)
        ax.set_xlim(-.5, shape[1]-.5)
        ax.set_ylim(shape[0]-.5, -.5)
        ax.set_title(title, fontsize=12, loc='left')
        ax.set_axis_off()

    fig, axes = plt.subplots(2, 2, figsize=(12, 11), facecolor='white')
    display(axes[0, 0], 'Cached photo — unchanged')
    display(axes[0, 1], 'Existing Google-informed baseline*', source_polygons)
    display(axes[1, 0], 'RoofSight — stock exported polygons', roof_polygons)
    display(axes[1, 1], 'Previous Phase 2 — rejected', previous_polygons)
    fig.text(.04, .035, '*Baseline boundaries were generated by our existing pipeline; Google supplies plane measurements, not these polygons.', fontsize=10)
    fig.text(.04, .015, 'Same image and scale · Includes solar data from Google · Single-house evaluation; no surveyed ground truth.', fontsize=10)
    fig.tight_layout(rect=(.02, .055, .98, .98))
    fig.savefig(output / 'comparison.png', dpi=150)
    plt.close(fig)

    geometry_only = labels_to_geojson(arrays['ransac'], manifest['bounds'], [], 50)
    (output / 'geometry-only-geojson.json').write_text(json.dumps(geometry_only, indent=2))
    geometry_only_polygons = [transform_ring(geo_to_crop(f['geometry']['coordinates'][0]), crop_to_common)
                              for f in geometry_only['features']]
    fig, axes = plt.subplots(1, 2, figsize=(12, 6.2), facecolor='white')
    display(axes[0], 'RoofSight geometry only — no RADIO fusion', geometry_only_polygons)
    display(axes[1], 'RoofSight full pipeline — RADIO fusion', roof_polygons)
    fig.text(.04, .03, 'Same cached inputs and export settings · Geometry-only comparison reuses the exact RANSAC labels · Includes solar data from Google', fontsize=9)
    fig.tight_layout(rect=(.02, .06, .98, .98))
    fig.savefig(output / 'vision-ablation.png', dpi=150)
    plt.close(fig)
    # Compare partitions without assuming numeric IDs survive split/relabel steps.
    ransac, fused, mask = arrays['ransac'], arrays['fused'], arrays['mask'] > 0
    rows = []
    disagreements = 0
    for identifier in sorted(set(np.unique(fused)) - {0}):
        selected = fused == identifier
        old, counts = np.unique(ransac[selected], return_counts=True)
        dominant = int(old[np.argmax(counts)])
        disagreements += int(selected.sum() - counts.max())
        info = next(p for p in planes if p['segment_id'] == identifier)
        exported_model_rmse = None
        if 'plane_normal' in info:
            yy, xx = np.nonzero(ndi.binary_erosion(selected, iterations=3))
            if len(xx):
                normal, d = np.array(info['plane_normal']), info['plane_d']
                predicted = -(normal[0]*xx*.1 + normal[1]*yy*.1 + d)/normal[2]
                exported_model_rmse = float(np.sqrt(np.mean((predicted - arrays['dsm'][yy, xx])**2)))
        rows.append({'fused_id': int(identifier), 'area_horizontal_m2': float(selected.sum()*.01),
                     'dominant_ransac_id': dominant,
                     'dominant_ransac_fraction': float(counts.max()/selected.sum()),
                     'upstream_attached_plane_model_interior_rmse_m': exported_model_rmse,
                     'own_height_refit': rmse_for_region(selected, arrays['dsm'])})
    # Keep raw export untouched. Repair ONLY diagnostic copies so invalid stock
    # polygons can be measured without hiding their failure in the report.
    metric_polygons = [make_valid(p) for p in stock_polygons]
    union = unary_union(metric_polygons)
    sum_area = sum(p.area for p in metric_polygons)
    exported_mask = np.zeros(mask.shape, dtype=np.uint8)
    for polygon in metric_polygons:
        # Rasterization diagnostic only; use native pixel-center coordinates.
        from rasterio.features import rasterize
        exported_mask |= rasterize([(polygon, 1)], out_shape=mask.shape,
                                   transform=Affine.identity(), dtype='uint8')
    original, clean = set(np.unique(ransac)) - {0}, set(np.unique(fused)) - {0}
    partitions_equivalent = all(len(np.unique(fused[ransac == k])) == 1 for k in original) and all(
        len(np.unique(ransac[fused == k])) == 1 for k in clean) and np.array_equal(ransac > 0, fused > 0)
    report = {'house_count': 1, 'inference_network_requests': 0,
              'comparison_frame': 'Original aligned cached RGB; stock export converted back through its own bounds and native raster affine',
              'cold_warm_identical': {k: bool(np.array_equal(cold[k], arrays[k])) for k in ['ransac','radio','fused']},
              'ransac_regions': len(original), 'fused_regions': len(clean),
              'exported_polygons': len(geo['features']),
              'geometry_only_exported_polygons': len(geometry_only['features']),
              'geometry_and_final_partitions_equivalent_ignoring_label_ids': partitions_equivalent,
              'exported_vertices_excluding_closure': sum(len(f['geometry']['coordinates'][0])-1 for f in geo['features']),
              'fused_pixels_not_in_their_dominant_geometry_region': disagreements,
              'radio_roof_fraction_inside_building': float(np.mean(arrays['radio'][mask] < 6)),
              'exported_polygon_validity': [p.is_valid for p in stock_polygons],
              'exported_polygon_validity_details': [explain_validity(p) for p in stock_polygons],
              'area_diagnostic_basis': 'make_valid copies only; original exported GeoJSON and displayed contours unchanged',
              'exported_projected_area_native_m2': float(sum_area*.01),
              'exported_overlap_native_m2': float((sum_area-union.area)*.01),
              'building_mask_area_m2': float(mask.sum()*.01),
              'mask_area_not_covered_by_export_m2': float((mask & ~(exported_mask>0)).sum()*.01),
              'export_area_outside_mask_m2': float(((exported_mask>0)&~mask).sum()*.01),
              'regions': rows,
              'limits': ['No independent metric ground truth',
                         'User annotation never read by inference or this metric computation',
                         'Own-region height refits measure internal consistency, not physical accuracy',
                         'Contour simplification is not shared-edge topology solving',
                         'One house and small crop cannot establish fleet performance or production cost']}
    (output / 'evaluation.json').write_text(json.dumps(report, indent=2))
    print(json.dumps({k:v for k,v in report.items() if k not in ['regions','limits']}, indent=2))


if __name__ == '__main__':
    main()
